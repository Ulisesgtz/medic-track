"""Generate internal/growth/whodata_gen.go from the WHO percentile tables (specs/063-curvas-crecimiento, research R1).

The Excel files are NOT in the repository (WHO terms of use: reproduction for commercial purposes needs written permission;
see specs/063-curvas-crecimiento/research.md). Download them from who.int into one folder and run:

    python -I tools/whogrowth/convert.py <folder> > internal/growth/whodata_gen.go && gofmt -w internal/growth/whodata_gen.go

Files expected in <folder> (names as published by WHO, renamed where the CDN adds a suffix):
    tab_wfa_{boys,girls}_p_0_5.xlsx          Child Growth Standards, weight-for-age, 0-60 months
    wfa_5_10_{boys,girls}.xlsx               Growth Reference 2007, weight-for-age, 61-120 months
    tab_lhfa_{boys,girls}_p_0_2.xlsx         Child Growth Standards, length-for-age, 0-24 months (lying)
    tab_lhfa_{boys,girls}_p_2_5.xlsx         Child Growth Standards, height-for-age, 24-60 months (standing)
    hfa-{boys,girls}-perc-who2007-exp.xlsx   Growth Reference 2007, height-for-age, 61-228 months

Only the published P3, P15, P50, P85 and P97 columns are kept — never L, M, S: the app draws the reference and never computes a
child's percentile (Principio I).
"""
import sys
import openpyxl

COLS = ("P3", "P15", "P50", "P85", "P97")


def read(path, first=None, last=None):
    ws = openpyxl.load_workbook(path, read_only=True, data_only=True).active
    rows = list(ws.iter_rows(values_only=True))
    head = [str(h).strip() for h in rows[0]]
    idx = [head.index(c) for c in COLS]
    out = []
    for r in rows[1:]:
        if r[0] is None:
            continue
        m = int(r[0])
        if (first is not None and m < first) or (last is not None and m > last):
            continue
        out.append((m, [float(r[i]) for i in idx]))
    return out


def series(folder, sex):
    other = "boys" if sex == "boys" else "girls"
    weight = read(f"{folder}/tab_wfa_{other}_p_0_5.xlsx") + read(f"{folder}/wfa_5_10_{other}.xlsx", 61, 120)
    height = (
        read(f"{folder}/tab_lhfa_{other}_p_0_2.xlsx", 0, 23)
        + read(f"{folder}/tab_lhfa_{other}_p_2_5.xlsx", 24, 60)
        + read(f"{folder}/hfa-{other}-perc-who2007-exp.xlsx", 61, 228)
    )
    for s in (weight, height):
        months = [m for m, _ in s]
        assert months == list(range(months[0], months[-1] + 1)), "months must be consecutive"
    return weight, height


def fmt(v):
    s = f"{v:.3f}".rstrip("0").rstrip(".")
    return s


def emit(name, rows):
    print(f"var {name} = []Point{{")
    for m, p in rows:
        print(f"\t{{{m}, {fmt(p[0])}, {fmt(p[1])}, {fmt(p[2])}, {fmt(p[3])}, {fmt(p[4])}}},")
    print("}")
    print()


def main():
    folder = sys.argv[1]
    print("// Code generated by tools/whogrowth/convert.py; DO NOT EDIT.")
    print("//")
    print("// Source: World Health Organization. WHO Child Growth Standards (2006): weight-for-age and length/height-for-age,")
    print("// 0-60 months; WHO Growth Reference 2007: weight-for-age 61-120 months and height-for-age 61-228 months.")
    print("// https://www.who.int/tools/child-growth-standards and https://www.who.int/tools/growth-reference-data-for-5to19-years")
    print("// Only the published P3, P15, P50, P85 and P97 (length lying until 23 months, height standing from 24).")
    print("// Shown only behind WHO_GROWTH_REFERENCE_ENABLED until WHO's written permission (specs/063, research R1).")
    print()
    print("package growth")
    print()
    for sex, go in (("girls", "Female"), ("boys", "Male")):
        weight, height = series(folder, sex)
        emit(f"weight{go}", weight)
        emit(f"height{go}", height)


if __name__ == "__main__":
    main()
